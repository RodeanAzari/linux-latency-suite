#!/usr/bin/env python3
"""The README matrix (§11): 5 classes x configs, p50 / p99 / p99.9.

Usage: table.py [SUMMARY_CSV] [README]
  defaults: results/summary.csv, and print to stdout.
  With README, replaces the text between <!-- matrix:begin --> and
  <!-- matrix:end --> in it instead of printing.

One representative test per §2 class. Each cell is the median over a
config's runs of each percentile, in the unit named in the column header.
Whether a difference between rows is real is deltas.py's job (§3.6), not
this table's: it only shows where each config sits.
"""
import json
import re
import sys

import pandas as pd

CLASSES = [  # (test, header, scale from summary.csv's unit to the shown one)
    ("sched_latency", "timer wakeup (µs)", 1),
    ("syscall_getppid", "getppid() (ns)", 1000),
    ("ctxswitch_2_3", "ctx switch, cross-core (µs)", 1),
    ("ipc_udp_2_3", "UDP loopback RTT (µs)", 1),
    ("memlat_65536K_4K", "DRAM load, 4K pages (ns)", 1),
]
METRICS = ["p50", "p99", "p99.9"]
BEGIN, END = "<!-- matrix:begin -->", "<!-- matrix:end -->"


def fmt(v):
    return "–" if pd.isna(v) else f"{v:.3g}" if v < 100 else f"{v:.0f}"


def tables(summary):
    d = pd.read_csv(summary)
    cfgs = json.load(open("configs/matrix.json"))["configs"]
    med = d.groupby(["config", "load", "test"])[METRICS].median()
    nruns = d.groupby(["config", "load"])["run"].nunique()
    out = []
    for load in ("idle", "loaded"):
        out += [f"**{load}** (p50 / p99 / p99.9)", "",
                "| config | runs | " + " | ".join(h for _, h, _ in CLASSES) + " |",
                "|---|---:|" + "---:|" * len(CLASSES)]
        for c in cfgs:
            name = c["name"]
            if (name, load) not in nruns:
                out.append(f"| `{name}` | 0 |" + " – |" * len(CLASSES))
                continue
            cells = []
            for test, _, k in CLASSES:
                if (name, load, test) in med.index:
                    cells.append(" / ".join(fmt(med.loc[(name, load, test), m] * k) for m in METRICS))
                else:
                    cells.append("–")
            label = f"*`{name}`*" if c.get("spot") else f"`{name}`"
            out.append(f"| {label} | {nruns[(name, load)]} | " + " | ".join(cells) + " |")
        out.append("")
    out.append("Median of each config's runs; the spot row (italic) is baseline + one knob, "
               "not cumulative. Generated by `analysis/table.py` from `results/summary.csv`.")
    return "\n".join(out)


def splice(readme, body):
    s = open(readme, encoding="utf-8").read()
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if len(pat.findall(s)) != 1:
        sys.exit(f"{readme}: need exactly one {BEGIN} ... {END} block")
    s = pat.sub(lambda _: f"{BEGIN}\n{body}\n{END}", s)
    open(readme, "w", encoding="utf-8", newline="\n").write(s)


if __name__ == "__main__":
    a = sys.argv[1:]
    body = tables(a[0] if a else "results/summary.csv")
    if len(a) > 1:
        splice(a[1], body)
        print(f"matrix -> {a[1]}")
    else:
        print(body)
